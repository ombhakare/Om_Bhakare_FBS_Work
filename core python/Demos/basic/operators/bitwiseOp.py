###bitwise operator
## 1. & (AND)
#if both bits are 1 then consider 0 otherwise 1
print(13 & 6)

#2. | (OR)
#if both bits are 0 then consider 0 otherwise 1
print(13 | 6)

# 3. ^ (XOR)
#if both bits are different then consider 1 otherwise 0
print(13 ^ 6)

# 4. ~(NOT)
print(~10)
print(~20)

# 5. << (left shift)
print(5<<2)
print(4<<3)

# 6. >> (right shift)
print(20 >> 2)
print(23 >> 3)