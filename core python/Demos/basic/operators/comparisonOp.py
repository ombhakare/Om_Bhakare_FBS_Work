#### Relational or comparison operator

## 1. == (exact equals too)
print(10 == 10)

## 2. != (not equals to)
print(10 != 30)

## 3. > (greater then)
print(10 > 20)

## 4. >= (greater than or equals to)
print(10 != 30)


## 5. < (less than)
print(10 < 20)

## 6. <= (less than equals to)
print (40 <= 45)